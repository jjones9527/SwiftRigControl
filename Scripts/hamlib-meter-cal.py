#!/usr/bin/env python3
"""Generate Swift TX-meter calibration tables from Hamlib's Yaesu newcat backends.

Reads each model's `.swr_cal`, `.alc_cal`, `.rfpower_meter_cal`,
`.comp_meter_cal`, `.vd_meter_cal` and `.id_meter_cal` assignments from
`~/Developer/hamlib/rigs/yaesu/<model>.c`, resolves the named tables
(`#define NAME { n, { {raw, value}, ... } }` in the backend headers, and
the `yaesu_default_*_cal` tables in newcat.c that newcat_get_level falls
back to), and prints
Sources/RigControl/Protocols/Yaesu/YaesuCATProtocol+MeterCalibration.swift.

Usage: Scripts/hamlib-meter-cal.py > Sources/RigControl/Protocols/Yaesu/YaesuCATProtocol+MeterCalibration.swift
"""

import glob
import os
import re
import subprocess

HAMLIB = os.path.expanduser(os.environ.get("HAMLIB_SRC", "~/Developer/hamlib"))
YAESU = os.path.join(HAMLIB, "rigs", "yaesu")
KINDS = ["swr", "alc", "rfpower_meter", "comp_meter", "vd_meter", "id_meter"]
SWIFT = {"swr": "swr", "alc": "alc", "rfpower_meter": "rfPower",
         "comp_meter": "comp", "vd_meter": "voltage", "id_meter": "current"}

# Hamlib backend file → (Swift preset name, catalog models it covers).
MODELS = {
    "ft450.c": ("ft450", "FT-450, FT-450D"),
    "ft710.c": ("ft710", "FT-710"),
    "ft891.c": ("ft891", "FT-891"),
    "ft950.c": ("ft950", "FT-950"),
    "ft991.c": ("ft991", "FT-991, FT-991A"),
    "ftdx10.c": ("ftdx10", "FTDX-10"),
    "ftdx101.c": ("ftdx101D", "FTDX-101D"),
    "ftdx101mp.c": ("ftdx101MP", "FTDX-101MP"),
    "ft1200.c": ("ftdx1200", "FTDX-1200"),
    "ft2000.c": ("ft2000", "FT-2000"),
    "ft3000.c": ("ftdx3000", "FTDX-3000"),
    "ft5000.c": ("ftdx5000", "FTDX-5000"),
    "ft9000.c": ("ftdx9000", "FTDX-9000"),
    "ftx1/ftx1.c": ("ftx1", "FTX-1"),
}


def sources():
    text = ""
    for path in glob.glob(os.path.join(YAESU, "**", "*.[ch]"), recursive=True):
        text += open(path, errors="replace").read() + "\n"
    return text


def parse_points(body):
    return [(int(a), float(b)) for a, b in re.findall(r"\{\s*(-?\d+)\s*,\s*(-?[\d.]+)f?\s*\}", body)]


def defines(text):
    """NAME -> [(raw, value)] for #define tables and const cal tables."""
    joined = text.replace("\\\n", " ")
    found = {}
    for name, body in re.findall(r"#define\s+(\w+_CAL)\s+(\{.*)", joined):
        found[name] = parse_points(body)
    for name, body in re.findall(r"const\s+cal_table_float_t\s+(\w+)\s*=\s*(\{.*?\});", text, re.S):
        found[name] = parse_points(body)
    return found


def main():
    text = sources()
    tables = defines(text)
    commit = subprocess.run(["git", "-C", HAMLIB, "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True).stdout.strip()
    out = [
        "import Foundation",
        "",
        "// Generated by Scripts/hamlib-meter-cal.py from Hamlib " + commit + " (rigs/yaesu).",
        "// Do not edit by hand; regenerate after a Hamlib update.",
        "",
        "extension YaesuCATProtocol {",
        "    /// TX-meter calibration for one newcat model, from its Hamlib caps",
        "    /// (`.swr_cal`, `.alc_cal`, `.rfpower_meter_cal`, `.comp_meter_cal`,",
        "    /// `.vd_meter_cal`, `.id_meter_cal`). A meter without a model table",
        "    /// uses Hamlib's `yaesu_default_*_cal`, as `newcat_get_level` does.",
        "    public struct MeterCalibration: Sendable, Equatable {",
    ]
    for kind in KINDS:
        out.append(f"        /// Raw `RM` reading → {kind.replace('_', ' ')} value.")
        out.append(f"        public let {SWIFT[kind]}: FloatCalibrationTable")
    out += ["", "        /// Hamlib's `yaesu_default_*_cal` tables (newcat.c).",
            "        public static let `default` = MeterCalibration("]
    defaults = []
    for kind in KINDS:
        name = f"yaesu_default_{kind}_cal"
        defaults.append(f"            {SWIFT[kind]}: {table(tables[name])}")
    out.append(",\n".join(defaults))
    out.append("        )")
    for file, (preset, models) in MODELS.items():
        caps = open(os.path.join(YAESU, file), errors="replace").read()
        assigned = dict(re.findall(r"\.(\w+)_cal\s*=\s*(\w+)", caps))
        out += ["", f"        /// {models} (Hamlib `{file}`)."]
        out.append(f"        public static let {preset} = MeterCalibration(")
        for index, kind in enumerate(KINDS):
            name = assigned.get(kind)
            comma = "," if index < len(KINDS) - 1 else ""
            if name and name in tables:
                out.append(f"            {SWIFT[kind]}: {table(tables[name])}{comma}  // {name}")
            else:
                out.append(f"            {SWIFT[kind]}: `default`.{SWIFT[kind]}{comma}")
        out.append("        )")
    out += ["    }", "}", ""]
    print("\n".join(out))


def table(points):
    body = ", ".join(f"({r}, {v:g})" for r, v in points)
    return f"FloatCalibrationTable([{body}])"


if __name__ == "__main__":
    main()
